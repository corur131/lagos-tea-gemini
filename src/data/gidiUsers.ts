export function createLightweightComment(
  id: string,
  userId: keyof typeof GIDI_LIGHTWEIGHT_USERS | string,
  text: string,
  overrides?: Partial<SocialComment>
): SocialComment {
  const user = GIDI_LIGHTWEIGHT_USERS[userId] || {
    id: userId,
    name: userId.replace(/_/g, ' '),
    handle: `@${userId}`,
    avatarColor: '#64748b',
    bgGradient: 'from-neutral-700 to-neutral-900',
    role: 'GidiGram User',
  };

  return {
    id,
    authorId: user.id,
    authorName: user.name,
    authorHandle: user.handle,
    isVerified: user.isVerified ?? false,
    avatarType: 'fan',
    avatarColor: user.avatarColor,
    text,
    likes: overrides?.likes ?? 12,
    timestamp: overrides?.timestamp ?? '20m ago',
    ...overrides,
  };
}
